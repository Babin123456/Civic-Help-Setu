const publishContact = (storage, overrides = {}) => {
  const draft = createContact(contactPayload(overrides), operator, {
    storage,
    now: NOW,
    idempotencyKey: `contact-${Math.random().toString(36).slice(2, 12)}`,
  });
  submitContact(draft.contact.id, operator, {
    storage,
    now: NOW,
    expectedVersion: draft.contact.version,
  });
  const submitted = getContactDetail(draft.contact.id, operator, { storage, now: NOW });
  const approved = reviewContact(
    draft.contact.id,
    CONTACT_ACTION.APPROVE,
    {
      verificationMethod: 'Official UP Police portal checked manually',
      lastVerifiedAt: '2026-11-20',
      reason: 'Checked the official UP Police page before publishing.',
      expectedVersion: submitted.version,
    },
    reviewer,
    { storage, now: NOW }
  );
  return approved.contact;
};

