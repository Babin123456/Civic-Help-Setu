/**
 * Civic Expense Export Service (#647)
 *
 * Provides redacted expense exports for payment records attached to civic service journeys.
 * - Strips transaction identifiers, receipt numbers, and sensitive file attachments on demand.
 * - Preserves audit trail (service, amount, date, status, official category) without exposing private IDs.
 * - Generates Markdown, Plain Text, and JSON export formats for citizen reimbursement or tax reporting.
 */

import {
  getPaymentsForJourney,
  redactPaymentForExport,
  PAYMENT_RECORD_STATUS,
  formatCurrency,
} from './paymentService';

/**
 * Exports all payments for a service journey as markdown, with optional redaction.
 *
 * @param {string} serviceId - The civic service ID
 * @param {string} journeyId - The journey identifier
 * @param {Object} [options] - Export options
 * @param {boolean} [options.redact=false] - Whether to redact transaction identifiers
 * @returns {string} Markdown-formatted export string
 */
export function exportPaymentsMarkdown(serviceId, journeyId, options = {}) {
  const { redact = false } = options;
  const payments = getPaymentsForJourney(serviceId, journeyId);
  const exportDate = new Date().toISOString().split('T')[0];

  const header = [
    `# Civic Payment Export: ${serviceId}`,
    `**Journey ID:** ${journeyId}`,
    `**Export Date:** ${exportDate}`,
    `**Redacted:** ${redact}`,
  ].join('\n');

  if (!payments || payments.length === 0) {
    return `${header}\n\nNo payment records found. Record payments first using the Payment-Receipt Organizer.`;
  }

  const paymentBlocks = payments.map((payment, idx) => {
    const displayPayment = redact ? redactPaymentForExport(payment) : payment;
    const amountStr = formatCurrency(displayPayment.amountPaid || displayPayment.amount || 0, displayPayment.currency || 'INR');
    const receiptLine = displayPayment.receiptNumber
      ? `\n- **Receipt Number:** ${displayPayment.receiptNumber}`
      : (displayPayment.receipt?.fileName ? `\n- **Receipt Attachment:** ${displayPayment.receipt.fileName}` : '');

    const disputedNotice = displayPayment.isDisputed
      ? '\n- **Classification:** ⚠️ DISPUTED / UNOFFICIAL CHARGE'
      : '\n- **Classification:** Official Civic Fee';

    const refundLine = displayPayment.status === PAYMENT_RECORD_STATUS.REFUNDED && displayPayment.refundInfo
      ? `\n- **Refund:** ₹${displayPayment.refundInfo.refundAmount} refunded on ${displayPayment.refundInfo.refundDate} (${displayPayment.refundInfo.reason})`
      : '';

    return [
      `### Payment #${idx + 1} (${displayPayment.paymentDate})`,
      `- **Transaction ID:** ${displayPayment.id}`,
      `- **Amount:** ${amountStr}`,
      `- **Mode:** ${displayPayment.paymentMode}`,
      `- **Status:** ${displayPayment.status || 'confirmed'}${receiptLine}${disputedNotice}${refundLine}`,
      `- **Notes:** ${displayPayment.notes || '—'}`,
    ].join('\n');
  });

  return [
    header,
    '',
    '## Payment Records',
    '',
    paymentBlocks.join('\n\n'),
    '',
    '---',
    '> Export generated by Civic Help Setu.',
    `> Transaction identifiers redacted: ${redact}.`,
  ].join('\n');
}

/**
 * Exports all payments for a service journey as plain text, with optional redaction.
 *
 * @param {string} serviceId - The civic service ID
 * @param {string} journeyId - The journey identifier
 * @param {Object} [options] - Export options
 * @param {boolean} [options.redact=false] - Whether to redact transaction identifiers
 * @returns {string} Plain-text export string
 */
export function exportPaymentsPlainText(serviceId, journeyId, options = {}) {
  const { redact = false } = options;
  const markdown = exportPaymentsMarkdown(serviceId, journeyId, { redact });

  return markdown
    .replace(/^#+ /gm, '')
    .replace(/#(\d+)/g, 'No. $1')
    .replace(/\*\*(.*?)\*\*/g, '$1')
    .replace(/^> /gm, '')
    .replace(/^---$/gm, '----------------------------------------')
    .trim();
}

/**
 * Generates a summary export of total expenditures for a service journey,
 * including official totals, disputed totals, and refund counts.
 *
 * @param {string} serviceId - The civic service ID
 * @param {string} journeyId - The journey identifier
 * @param {Object} [options] - Export options
 * @param {boolean} [options.redact=false] - Whether to redact transaction identifiers
 * @returns {Object} Summary with totals and breakdown
 */
export function exportPaymentSummary(serviceId, journeyId, options = {}) {
  const { redact = false } = options;
  const payments = getPaymentsForJourney(serviceId, journeyId);

  const confirmedPayments = payments.filter(
    (p) => (p.status === 'confirmed' || p.status === 'completed' || p.status === PAYMENT_RECORD_STATUS.CONFIRMED) && !p.isDisputed
  );

  const refundedPayments = payments.filter(
    (p) => p.status === 'refunded' || p.status === PAYMENT_RECORD_STATUS.REFUNDED
  );

  const totalPaid = confirmedPayments.reduce(
    (sum, p) => sum + (p.amountPaid || p.amount || 0),
    0
  );

  const totalRefunded = refundedPayments.reduce(
    (sum, p) => sum + (p.refundInfo?.refundAmount || p.amountPaid || p.amount || 0),
    0
  );

  const netTotal = Math.max(0, totalPaid - totalRefunded);

  const processedPayments = redact
    ? payments.map((p) => redactPaymentForExport(p))
    : payments.map((p) => ({ ...p }));

  return {
    serviceId,
    journeyId,
    exportDate: new Date().toISOString().split('T')[0],
    redact,
    totalPaid,
    totalRefunded,
    netTotal,
    paymentCount: confirmedPayments.length,
    refundCount: refundedPayments.length,
    summaryNotes: redact
      ? 'Transaction identifiers redacted for privacy. Amounts and counts preserved.'
      : 'Full details included.',
    payments: processedPayments,
  };
}

/**
 * Exports payments for a service journey as CSV, with optional redaction.
 *
 * @param {string} serviceId - The civic service ID
 * @param {string} journeyId - The journey identifier
 * @param {Object} [options] - Export options
 * @param {boolean} [options.redact=false] - Whether to redact transaction identifiers
 * @returns {string} CSV-formatted export string
 */
export function exportPaymentsCsv(serviceId, journeyId, options = {}) {
  const { redact = false } = options;
  const payments = getPaymentsForJourney(serviceId, journeyId);

  const headers = ['Transaction ID', 'Date', 'Amount', 'Currency', 'Mode', 'Category', 'Receipt Number', 'Status', 'Disputed', 'Notes'];
  if (!payments || payments.length === 0) {
    return headers.join(',') + '\n';
  }

  const rows = payments.map((p) => {
    const display = redact ? redactPaymentForExport(p) : p;
    const fields = [
      `"${String(display.id || '').replace(/"/g, '""')}"`,
      `"${String(display.paymentDate || '').replace(/"/g, '""')}"`,
      Number(display.amountPaid || display.amount || 0),
      `"${String(display.currency || 'INR').replace(/"/g, '""')}"`,
      `"${String(display.paymentMode || '').replace(/"/g, '""')}"`,
      `"${String(display.feeCategory || 'government-statutory').replace(/"/g, '""')}"`,
      `"${String(display.receiptNumber || 'N/A').replace(/"/g, '""')}"`,
      `"${String(display.status || 'confirmed').replace(/"/g, '""')}"`,
      display.isDisputed ? 'YES' : 'NO',
      `"${String(display.notes || '').replace(/"/g, '""')}"`,
    ];
    return fields.join(',');
  });

  return [headers.join(','), ...rows].join('\n');
}

export default {
  exportPaymentsMarkdown,
  exportPaymentsPlainText,
  exportPaymentSummary,
  exportPaymentsCsv,
};
