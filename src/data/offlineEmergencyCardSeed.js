/**
 * Seeded official sources and public emergency contacts for the Offline
 * Emergency Civic Information Card (#761).
 *
 * Only public, organisation-level emergency contacts are included. Numbers are
 * taken from existing Civic Help Setu emergency helpline data or well-known
 * national emergency services. Each contact points at an official government
 * source and carries a manual verification date. No personal contact details,
 * resident records or uploaded documents are stored here.
 *
 * Dates are generated relative to the seed time so a fresh local demo always
 * has a mix of current, review-due and clearly outdated records.
 */

