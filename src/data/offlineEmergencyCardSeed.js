const DAY_MS = 24 * 60 * 60 * 1000;

const daysAgo = (now, days) => new Date(new Date(now).getTime() - days * DAY_MS).toISOString();

const source = ({
  id,
  title,
  publisher,
  officialUrl,
  jurisdictionId,
  sourceType,
  retrievedDaysAgo,
  now,
}) => ({
  id,
  title,
  publisher,
  officialUrl,
  jurisdictionId,
  sourceType,
  status: SOURCE_STATUS.ACTIVE,
  retrievedAt: daysAgo(now, retrievedDaysAgo),
  createdAt: daysAgo(now, 120),
  updatedAt: daysAgo(now, retrievedDaysAgo),
  createdBy: 'seed.official-sources',
  version: 1,
  schemaVersion: OFFLINE_CARD_SCHEMA_VERSION,
});

