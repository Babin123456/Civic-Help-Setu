// PII safeguarding regex patterns
export const AADHAAR_REGEX = /\b\d{4}\s?\d{4}\s?\d{4}\b/;
export const PAN_REGEX = /\b[A-Z]{5}[0-9]{4}[A-Z]\b/i;
export const PHONE_REGEX = /\b(\+91[-\s]?)?[6-9]\d{9}\b/;
export const EMAIL_REGEX = /\b[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Z|a-z]{2,}\b/;

export const sanitizeText = (val, maxLen = 2000) => {
  if (typeof val !== 'string') return '';
  return val
    .replace(/<[^>]*>/g, '') // Strip HTML tags to prevent XSS
    // eslint-disable-next-line no-control-regex
    .replace(/[\u0000-\u001f\u007f-\u009f]/g, '')
    .trim()
    .slice(0, maxLen);
};

export const checkForForbiddenPII = (val) => {
  if (typeof val !== 'string') return null;
  const detected = [];
  if (AADHAAR_REGEX.test(val)) detected.push('Contains 12-digit Aadhaar number pattern');
  if (PAN_REGEX.test(val)) detected.push('Contains PAN identifier pattern');
  if (PHONE_REGEX.test(val)) detected.push('Contains telephone contact number');
  if (EMAIL_REGEX.test(val)) detected.push('Contains private email address');
  return detected.length > 0 ? detected.join('; ') : null;
};

export const isValidHttpsUrl = (url) => {
  if (typeof url !== 'string' || !url.trim()) return false;
  try {
    const parsed = new URL(url);
    return parsed.protocol === 'https:';
  } catch {
    return false;
  }
};

/**
 * Validates a ProcurementNotice entity.
 */
export const validateProcurementNotice = (notice) => {
  const errors = [];
  if (!notice || typeof notice !== 'object') {
    return ['Procurement notice must be an object.'];
  }

  const id = sanitizeText(notice.id || '', 100);
  if (!id) errors.push('Notice ID is required.');

  const tenderRef = sanitizeText(notice.tenderRefNumber || '', 100);
  if (!tenderRef || tenderRef.length < 3) {
    errors.push('tenderRefNumber is required (min 3 characters).');
  }

  const title = sanitizeText(notice.title || '', 200);
  if (!title || title.length < 10) {
    errors.push('Notice title must be at least 10 characters.');
  }
  const piiTitle = checkForForbiddenPII(title);
  if (piiTitle) errors.push(`Title ${piiTitle}.`);

  if (!notice.category || !PROCUREMENT_CATEGORIES[notice.category]) {
    errors.push(`Category must be one of: ${Object.keys(PROCUREMENT_CATEGORIES).join(', ')}.`);
  }

  if (!notice.procurementMethod || !PROCUREMENT_METHODS[notice.procurementMethod]) {
    errors.push(`procurementMethod must be one of: ${Object.keys(PROCUREMENT_METHODS).join(', ')}.`);
  }

  const estimatedValue = Number(notice.estimatedValue);
  if (Number.isNaN(estimatedValue) || estimatedValue <= 0) {
    errors.push('estimatedValue must be a positive number.');
  }

  const pubDate = new Date(notice.publicationDate);
  const closeDate = new Date(notice.submissionDeadline);
  if (Number.isNaN(pubDate.getTime())) {
    errors.push('publicationDate must be a valid ISO date string.');
  }
  if (Number.isNaN(closeDate.getTime())) {
    errors.push('submissionDeadline must be a valid ISO date string.');
  }
  if (pubDate > closeDate) {
    errors.push('publicationDate cannot be later than submissionDeadline.');
  }

  if (notice.sourceUrl && !isValidHttpsUrl(notice.sourceUrl)) {
    errors.push('sourceUrl must be a secure HTTPS URL.');
  }

  return errors;
};

/**
 * Validates an AuditReview submission payload.
 */
export const validateAuditReviewPayload = (payload) => {
  const errors = [];
  if (!payload || typeof payload !== 'object') {
    return ['Review payload must be an object.'];
  }

  const flagId = sanitizeText(payload.flagId || '', 100);
  if (!flagId) errors.push('flagId is required.');

  if (!payload.disposition || !REVIEW_STATUSES[payload.disposition]) {
    errors.push(`disposition must be one of: ${Object.keys(REVIEW_STATUSES).join(', ')}.`);
  }

  const justification = sanitizeText(payload.justification || '', 2000);
  if (!justification || justification.length < 15) {
    errors.push('A documented justification of at least 15 characters is required.');
  }

  const piiJustification = checkForForbiddenPII(justification);
  if (piiJustification) {
    errors.push(`Justification ${piiJustification}. Do not include personal contact details.`);
  }

  if (payload.reviewerRole && !USER_ROLES[payload.reviewerRole]) {
    errors.push(`reviewerRole must be one of: ${Object.keys(USER_ROLES).join(', ')}.`);
  }

  if (payload.evidenceDocumentUrl && !isValidHttpsUrl(payload.evidenceDocumentUrl)) {
    errors.push('evidenceDocumentUrl must be a valid HTTPS URL.');
  }

  return errors;
};

/**
 * Validates a VendorEntity.
 */
export const validateVendorEntity = (vendor) => {
  const errors = [];
  if (!vendor || typeof vendor !== 'object') {
    return ['Vendor entity must be an object.'];
  }

  const id = sanitizeText(vendor.id || '', 100);
  if (!id) errors.push('Vendor ID is required.');

  const name = sanitizeText(vendor.name || '', 200);
  if (!name || name.length < 3) errors.push('Vendor name must be at least 3 characters.');

  return errors;
};

/**
 * Generates an immutable, cryptographic-style audit seal for audit decisions.
 */
export const generateAuditSeal = (flagId, reviewerId, disposition, timestamp) => {
  const seed = `${flagId}|${reviewerId}|${disposition}|${timestamp}|CIVIC_OPEN_CONTRACTING_v1`;
  let hash = 0x811c9dc5;
  for (let i = 0; i < seed.length; i += 1) {
    hash ^= seed.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193);
  }
  const unsigned = hash >>> 0;
  const p1 = (unsigned & 0xffff).toString(16).toUpperCase().padStart(4, '0');
  const p2 = ((unsigned >>> 16) & 0xffff).toString(16).toUpperCase().padStart(4, '0');
  return `AUDIT-SEAL-${p1}-${p2}`;
};
