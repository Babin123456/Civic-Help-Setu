import {
  Download,
  PlusCircle,
  RefreshCw,
  ShieldCheck,
  Smartphone,
  Users,
  WifiOff,
} from 'lucide-react';
import { OFFLINE_CARD_ROLES } from '../../services/offlineEmergencyCardConstants.js';

const ROLE_OPTIONS = [
  { id: OFFLINE_CARD_ROLES.CITIZEN, label: 'Citizen / public' },
  { id: OFFLINE_CARD_ROLES.OPERATOR, label: 'Operator' },
  { id: OFFLINE_CARD_ROLES.REVIEWER, label: 'Reviewer' },
  { id: OFFLINE_CARD_ROLES.ADMIN, label: 'Administrator' },
];

export default function OfflineEmergencyCardHeader({
  activeRole,
  onRoleChange,
  jurisdictions = [],
  jurisdictionId,
  onJurisdictionChange,
  isOnline,
  installed,
  selectedCount,
  onInstall,
  onRefresh,
  onExport,
  canInstall = true,
  canRefresh = true,
  canExport = true,
  onNewContact,
  canCreateContact = false,
  storage,
}) {
  return (
    <header style={{ marginBottom: '1.5rem' }}>
      <div
        style={{
          display: 'flex',
          flexWrap: 'wrap',
          justifyContent: 'space-between',
          alignItems: 'flex-start',
          gap: '1rem',
          marginBottom: '1rem',
        }}
      >
        <div>
          <span
            style={{
              fontSize: '0.72rem',
              fontWeight: 800,
              letterSpacing: '0.06em',
              textTransform: 'uppercase',
              color: 'var(--text-secondary)',
            }}
          >
            Verified local contacts · works without a connection
          </span>
          <div style={{ display: 'flex', alignItems: 'center', gap: '0.55rem', marginTop: '0.2rem' }}>
            <span
              aria-hidden="true"
              style={{
                width: 38,
                height: 38,
                borderRadius: 9,
                display: 'inline-flex',
                alignItems: 'center',
                justifyContent: 'center',
                background: 'rgba(220, 38, 38, 0.1)',
                color: '#b91c1c',
              }}
            >
              <ShieldCheck size={22} />
            </span>
            <h1 style={{ margin: 0, fontSize: '1.65rem', lineHeight: 1.2 }}>
              Offline Emergency Civic Information Card
            </h1>
          </div>
          <p style={{ margin: '0.45rem 0 0', maxWidth: '780px', color: 'var(--text-secondary)', fontSize: '0.92rem' }}>
            Save verified police, fire, ambulance and civic helplines to this device. Every contact
            shows the date a human last checked it and the official government source it came from.
            Emergency numbers are never generated by AI.
          </p>
        </div>

        <div style={{ display: 'flex', flexWrap: 'wrap', gap: '0.5rem' }}>
          {canCreateContact && onNewContact && (
            <button type="button" className="btn btn-primary" onClick={onNewContact}>
              <PlusCircle size={15} aria-hidden="true" /> New contact
            </button>
          )}
          {canInstall && onInstall && (
            <button type="button" className="btn btn-primary" onClick={onInstall}>
              <Smartphone size={15} aria-hidden="true" />
              {installed ? 'Reinstall card' : 'Install card'}
              {selectedCount > 0 ? ` (${selectedCount})` : ''}
            </button>
          )}
          {canRefresh && onRefresh && (
            <button type="button" className="btn btn-secondary" onClick={onRefresh}>
              <RefreshCw size={15} aria-hidden="true" /> Refresh
            </button>
          )}
          {canExport && onExport && (
            <button type="button" className="btn btn-secondary" onClick={onExport}>
              <Download size={15} aria-hidden="true" /> Export
            </button>
          )}
        </div>
      </div>

      <div
        style={{
          display: 'flex',
          flexWrap: 'wrap',
          alignItems: 'center',
          justifyContent: 'space-between',
          gap: '0.75rem',
          padding: '0.75rem 1rem',
          background: 'var(--bg-secondary)',
          border: '1px solid var(--border-main)',
          borderRadius: '0.75rem',
        }}
      >
        <div style={{ display: 'flex', alignItems: 'center', gap: '0.5rem', flexWrap: 'wrap' }}>
          <label htmlFor="offline-card-jurisdiction" style={{ fontSize: '0.85rem', fontWeight: 700 }}>
            Jurisdiction
          </label>
          <select
            id="offline-card-jurisdiction"
            value={jurisdictionId}
            onChange={(event) => onJurisdictionChange(event.target.value)}
            style={{
              padding: '0.4rem 0.6rem',
              borderRadius: 6,
              border: '1px solid var(--border-main)',
              background: 'var(--bg-surface)',
              color: 'var(--text-primary)',
              fontSize: '0.85rem',
            }}
          >
            {jurisdictions.map((jurisdiction) => (
              <option key={jurisdiction.id} value={jurisdiction.id}>
                {jurisdiction.name} — {jurisdiction.state}
              </option>
            ))}
          </select>
          <span
            style={{
              display: 'inline-flex',
              alignItems: 'center',
              gap: '0.3rem',
              fontSize: '0.78rem',
              color: isOnline ? '#15803d' : '#b45309',
              fontWeight: 700,
            }}
          >
            {isOnline ? <ShieldCheck size={14} aria-hidden="true" /> : <WifiOff size={14} aria-hidden="true" />}
            {isOnline ? 'Online' : 'Offline'}
          </span>
          {installed && (
            <span style={{ fontSize: '0.78rem', color: 'var(--text-secondary)' }}>
              Card installed on this device
            </span>
          )}
          {storage?.persisted === false && (
            <span style={{ fontSize: '0.78rem', color: '#b45309', fontWeight: 700 }}>
              This visit only — storage unavailable
            </span>
          )}
        </div>

        <div style={{ display: 'flex', alignItems: 'center', gap: '0.5rem', flexWrap: 'wrap' }}>
          <Users size={16} aria-hidden="true" style={{ color: 'var(--text-secondary)' }} />
          <label htmlFor="offline-card-role" style={{ fontSize: '0.82rem', fontWeight: 700 }}>
            Role perspective
          </label>
          <select
            id="offline-card-role"
            value={activeRole}
            onChange={(event) => onRoleChange(event.target.value)}
            style={{
              padding: '0.4rem 0.6rem',
              borderRadius: 6,
              border: '1px solid var(--border-main)',
              background: 'var(--bg-surface)',
              color: 'var(--text-primary)',
              fontSize: '0.82rem',
            }}
          >
            {ROLE_OPTIONS.map((role) => (
              <option key={role.id} value={role.id}>
                {role.label}
              </option>
            ))}
          </select>
          <span style={{ fontSize: '0.72rem', color: 'var(--text-secondary)', maxWidth: '42ch' }}>
            Demonstration perspective. Production roles come from the signed-in account; the
            service still enforces every permission.
          </span>
        </div>
      </div>
    </header>
  );
}
