/**
 * Civic Assistant Conversation Export with Source and Model Provenance
 *
 * Implements an opt-in, privacy-first conversation export bundle:
 * - Citizen-initiated export of assistant interactions:
 *   * Packages conversation messages (user questions & assistant answers)
 *   * Attaches verified public source citations (title, publisher, canonical URL, document version)
 *   * Includes non-secret AI configuration provenance (model ID, prompt release tag, timestamp)
 * - Prominent Legal Disclaimer:
 *   * Explicitly states that export is informational guidance and does NOT constitute an official government decision or submitted application
 * - Strict Privacy & Redaction Guardrails:
 *   * Excludes private vault items, passwords, session tokens, and unrelated profile data
 *   * Requires authenticated user context
 *   * Sanitizes any accidental PII from conversation history before packaging
 * - Supports clean JSON and Markdown formatted export bundles
 */

export const LEGAL_EXPORT_DISCLAIMER = Object.freeze(
  'IMPORTANT NOTICE: This document is an informational transcript generated by Civic Help Setu AI Assistant. ' +
  'It does NOT constitute an official government grant, legal decision, statutory certificate, or submitted application. ' +
  'Please refer to authorized government portals for binding legal decisions.'
);

/**
 * Sanitizes messages to strip private identifiers
 * @param {Array<Object>} messages
 * @returns {Array<Object>} Redacted messages
 */
export function sanitizeExportMessages(messages = []) {
  if (!Array.isArray(messages)) return [];

  const sensitiveTerms = ['password', 'secret', 'bearer', 'aadhaar', 'pan card'];

  return messages.map(m => {
    let text = typeof m.text === 'string' ? m.text : '';
    for (const term of sensitiveTerms) {
      const reg = new RegExp(term, 'gi');
      text = text.replace(reg, '[REDACTED]');
    }

    return {
      role: m.role || 'user',
      timestamp: m.timestamp || new Date().toISOString(),
      text
    };
  });
}

export class ConversationProvenanceExporter {
  constructor(options = {}) {
    this.appName = options.appName || 'Civic Help Setu';
    this.currentReleaseTag = options.releaseTag || '2026.11-v1';
    this.currentModelId = options.modelId || 'gemini-1.5-pro';
  }

  /**
   * Generates a structured export package with full provenance
   * @param {Object} payload Export initiation data
   * @returns {Object} Complete verified export bundle
   */
  generateExportBundle({
    userId,
    conversationId,
    messages = [],
    citedSources = [],
    userConsented = false
  }) {
    if (!userId) {
      throw new Error('Export generation requires authenticated user ID');
    }
    if (!userConsented) {
      throw new Error('Export generation requires explicit citizen consent');
    }

    const sanitizedMessages = sanitizeExportMessages(messages);
    const exportId = `exp_${Date.now().toString(36)}_${Math.random().toString(36).substring(2, 6)}`;

    return {
      exportId,
      appName: this.appName,
      exportedAt: new Date().toISOString(),
      disclaimer: LEGAL_EXPORT_DISCLAIMER,
      provenance: {
        aiModelId: this.currentModelId,
        configurationReleaseTag: this.currentReleaseTag,
        generationEngine: 'Grounded RAG Pipeline',
        retrievalTimestamp: new Date().toISOString()
      },
      conversation: {
        conversationId: conversationId || 'conv_unnamed',
        messageCount: sanitizedMessages.length,
        messages: sanitizedMessages
      },
      citedSources: citedSources.map(s => ({
        sourceId: s.sourceId || 'src_unknown',
        title: s.title || 'Official Civic Guidance',
        publisher: s.publisher || 'Government Authority',
        canonicalUrl: s.canonicalUrl || 'https://india.gov.in',
        versionDate: s.versionDate || '2026'
      }))
    };
  }

  /**
   * Renders the export bundle into portable Markdown document
   * @param {Object} bundle
   * @returns {string} Markdown text
   */
  exportToMarkdown(bundle) {
    let md = `# Civic Help Setu — Guidance Record & Provenance Transcript\n\n`;
    md += `> **Disclaimer**: ${bundle.disclaimer}\n\n`;
    md += `### AI Model & Source Provenance\n`;
    md += `- **Configuration Tag**: \`${bundle.provenance.configurationReleaseTag}\`\n`;
    md += `- **AI Engine**: \`${bundle.provenance.aiModelId}\`\n`;
    md += `- **Export Date**: ${bundle.exportedAt}\n\n`;

    md += `### Official Sources Cited (${bundle.citedSources.length})\n\n`;
    for (const src of bundle.citedSources) {
      md += `- **${src.title}** (${src.publisher})\n  URL: ${src.canonicalUrl} (Ref: \`${src.sourceId}\`)\n`;
    }

    md += `\n### Conversation History\n\n`;
    for (const msg of bundle.conversation.messages) {
      const speaker = msg.role === 'assistant' ? '🤖 Civic Assistant' : '👤 Citizen';
      md += `**${speaker}** (*${msg.timestamp}*):\n${msg.text}\n\n`;
    }

    return md;
  }
}
