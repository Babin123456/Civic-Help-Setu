export const CIVIC_AGENT_SCENARIOS = Object.freeze(
  RAW_SCENARIOS.map((scenario) => {
    const res = validateEvalScenario(scenario);
    if (!res.valid) {
      throw new Error(`Invalid built-in scenario ${scenario.id}: ${res.errors.join('; ')}`);
    }
    return Object.freeze(res.value);
  })
);

/**
 * Filters built-in synthetic scenarios by category, language, or jurisdiction.
 * @param {Object} filters
 * @returns {Array<Object>}
 */
export function filterScenarios({ category = 'all', language = 'all', jurisdiction = 'all' } = {}) {
  return CIVIC_AGENT_SCENARIOS.filter((s) => {
    if (category && category !== 'all' && s.category !== category) return false;
    if (language && language !== 'all' && s.language !== language) return false;
    if (jurisdiction && jurisdiction !== 'all' && s.jurisdiction !== jurisdiction.toLowerCase()) {
      return false;
    }
    return true;
  });
}
